#!/usr/bin/env node
//
// generate-tester-templates.mjs
//
// Writes the request templates for the plugin API Tester (DataInteractiveAPITester in the
// codap-data-interactives repo) from the request examples in v3/doc/plugin-api/resources/.
//
// tester-templates.mjs decides which examples become templates, names them, and finds the
// problems that would leave one out; this script writes them, or checks a copy.
//
// Templates with no counterpart in the reference live in the tester's own tests.json; this
// script does not touch that file.
//
// Usage: npm run plugin-api:tester         (assumes codap-data-interactives is cloned beside codap)
//        npm run plugin-api:tester:check   (exit 1 if the tester's copy is missing or stale, 2 if the
//                                          reference's examples have problems)
//        node generate-tester-templates.mjs --out <file> [--check]
// A later --out wins, so `npm run plugin-api:tester -- --out <file>` writes elsewhere.
//
import { readFileSync, writeFileSync, existsSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { readInventory } from "./inventory.mjs"
import { buildTesterTemplates } from "./tester-templates.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const resourcesDir = join(here, "..", "..", "doc", "plugin-api", "resources")

const usage = "usage: generate-tester-templates.mjs --out <file> [--check]"
const args = process.argv.slice(2)
const outIndex = args.lastIndexOf("--out")
const outPath = outIndex >= 0 ? args[outIndex + 1] : undefined
const check = args.includes("--check")
if (!outPath || outPath.startsWith("--")) {
  console.error(usage)
  process.exit(1)
}

// Exit codes: 1 for usage, a missing directory or file, or an out-of-date file; 2 for problems in
// the reference's examples, so CI can tell the two apart.
const { templates, problems } = buildTesterTemplates(resourcesDir, readInventory())
if (problems.length) {
  problems.forEach(({ file, message }) => console.error(`${file}: ${message}`))
  process.exit(2)
}
const output = JSON.stringify({
  $comment: "Generated by v3/scripts/plugin-api/generate-tester-templates.mjs in the codap " +
            "repo, from the request examples in v3/doc/plugin-api/resources/. Do not edit by " +
            "hand: change the reference and regenerate. Hand-made templates go in tests.json.",
  templates
}, null, 2) + "\n"

if (!existsSync(dirname(outPath))) {
  console.error(`${dirname(outPath)} not found; clone codap-data-interactives beside the codap repo, or pass --out`)
  process.exit(1)
}

if (check) {
  if (!existsSync(outPath)) {
    console.error(`${outPath} is missing; pull the codap-data-interactives clone, or regenerate it with --out`)
    process.exit(1)
  }
  if (readFileSync(outPath, "utf8") !== output) {
    console.error(`${outPath} is out of date with the reference; regenerate it with --out`)
    process.exit(1)
  }
  console.log(`${outPath} is up to date (${templates.length} templates)`)
} else {
  writeFileSync(outPath, output)
  console.log(`wrote ${templates.length} templates to ${outPath}`)
}
